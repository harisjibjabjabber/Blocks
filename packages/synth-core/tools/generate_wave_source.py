"""Generate original bandlimited Fourier tables; numpy needed only to regenerate.

No sampled instruments or third-party oscillator source. Runtime uses checked-in
immutable floats, so neither table generation nor allocation occurs in render.
"""
from pathlib import Path
import json
import hashlib
import numpy as np

root = Path(__file__).resolve().parents[1]
limits = [1,2,3,4,5,6,8,10,13,17,22,28,36,46,59,76,98,126,162,208,267,343,440,565,725,931,1196,1536,1973,2535,3257]
def literal(x):
    text = format(float(np.float32(x)), '.9g')
    return text + ('f' if '.' in text or 'e' in text else '.0f')

chunks = ['// Generated by tools/generate_wave_source.py. Original Fourier coefficients.\n#pragma once\nnamespace blocks_detail { namespace studio_tables {\n']
sizes = []
for level, limit in enumerate(limits):
    size = max(2048, 1 << (8 * limit - 1).bit_length())
    sizes.append(size)
    h = np.arange(1, limit + 1)
    for wave in ('saw', 'triangle'):
        spectrum = np.zeros(size // 2 + 1, dtype=complex)
        if wave == 'saw':
            spectrum[h] = 1j * size / (np.pi * h)
        else:
            spectrum[h] = np.where(h % 2, size * 4 / (np.pi**2 * h**2), 0)
        samples = np.fft.irfft(spectrum)
        chunks.append(f'inline constexpr float {wave}_{level}[{size}]={{\n')
        for start in range(0, size, 8):
            chunks.append(','.join(literal(x) for x in samples[start:start+8]) + ',\n')
        chunks.append('};\n')
chunks.append('struct Level {unsigned harmonic,size;const float *saw,*triangle;};\n')
chunks.append('inline constexpr Level levels[]={\n')
for level, (limit, size) in enumerate(zip(limits, sizes)):
    chunks.append(f'{{{limit},{size},saw_{level},triangle_{level}}},\n')
chunks.append('};\ninline constexpr unsigned count=sizeof(levels)/sizeof(levels[0]);\n}}\n')
target = root/'src/wave_source_tables.h'
target.write_text(''.join(chunks), encoding='utf-8', newline='\n')
print(json.dumps({'file':str(target),'levels':len(limits),'float_data_bytes':sum(sizes)*2*4,'source_bytes':target.stat().st_size,'max_harmonics':limits[-1],'sha256':hashlib.sha256(target.read_bytes()).hexdigest()}))
