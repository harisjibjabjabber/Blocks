"""Regenerate original immutable waveform tables; stdlib only.

Run from any directory. No generation, allocation, or trigonometric harmonic
summation is needed when a synth instance is constructed or rendered.
"""
import math
from pathlib import Path

N = 2048
LIMITS = [1, 3, 7, 15, 31, 63, 127, 255]

def number(value):
    result = format(value, '.9g')
    if '.' not in result and 'e' not in result:
        result += '.0'
    return result + 'f'

def row(values):
    return ','.join(number(v) for v in values)

lines = ['// Generated by tests/generate_wave_tables.py. Original mathematical tables.',
         '#ifndef BLOCKS_WAVE_TABLES_H', '#define BLOCKS_WAVE_TABLES_H',
         'namespace blocks_detail {', 'constexpr unsigned waveTableSize=2048;',
         'constexpr unsigned triangleLimits[8]={1,3,7,15,31,63,127,255};',
         'constexpr float sineTable[2049]={' + row([math.sin(2*math.pi*i/N) for i in range(N)] + [0]) + '};',
         'constexpr float triangleTables[8][2049]={']
for limit in LIMITS:
    values = [8/math.pi**2 * sum(math.cos(2*math.pi*h*i/N)/h**2 for h in range(1, limit+1, 2)) for i in range(N)]
    lines.append('{' + row(values + [values[0]]) + '},')
lines += ['};', '}', '#endif', '']
Path(__file__).resolve().parents[1].joinpath('src/wave_tables.h').write_text('\n'.join(lines), encoding='utf-8')
