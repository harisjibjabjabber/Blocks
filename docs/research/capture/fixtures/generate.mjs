function mulberry32(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const NS = 1e9;
const ns = (sec) => Math.round(sec * NS);

class Session {
  constructor(id, seed) {
    this.id = id;
    this.seed = seed;
    this.r = mulberry32(seed);
    this.events = [];
    this.order = 0;
  }
  rand(a, b) { return a + (b - a) * this.r(); }
  pick(arr) { return arr[Math.floor(this.r() * arr.length)]; }
  // approx gaussian (Irwin-Hall), sd in seconds
  jit(sdMs) { let s = 0; for (let i = 0; i < 6; i++) s += this.r(); return ((s - 3) / Math.sqrt(0.5)) * (sdMs / 1000) / Math.sqrt(2); }
  add(tSec, type, d1, d2, o = {}) {
    if (tSec < 0) throw new Error(this.id + ": negative time " + tSec);
    this.events.push({ tNs: ns(tSec), src: o.src ?? "kbd", port: o.port ?? "A", ch: o.ch ?? 1, type, d1, d2, _o: this.order++ });
  }
  note(t, pitch, vel, dur, o = {}) {
    this.add(t, "on", pitch, Math.max(1, Math.min(127, Math.round(vel))), o);
    if (dur !== null) {
      if (o.vel0Off) this.add(t + dur, "on", pitch, 0, o);
      else this.add(t + dur, "off", pitch, o.relVel ?? 64, o);
    }
  }
  chord(t, pitches, vel, dur, spreadMs = 0, o = {}) {
    // rolled/staggered chord: lowest note first
    pitches.forEach((p, i) => {
      const off = pitches.length > 1 ? (spreadMs / 1000) * (i / (pitches.length - 1)) : 0;
      this.note(t + off, p, vel - i * 3, dur - off, o);
    });
  }
  cc(t, num, val, o = {}) { this.add(t, "cc", num, val, o); }
  pedal(tDown, tUp, num = 64, o = {}) { this.cc(tDown, num, 127, o); if (tUp !== null) this.cc(tUp, num, 0, o); }
  finalize() {
    this.events.sort((a, b) => a.tNs - b.tNs || a._o - b._o);
    return this.events.map((e, i) => ({ seq: i + 1, tNs: e.tNs, src: e.src, port: e.port, ch: e.ch, type: e.type, d1: e.d1, d2: e.d2 }));
  }
}

// beat clock: beat index (float, quarter notes) -> seconds
const clock = (bpm, originSec) => (beat) => originSec + (beat * 60) / bpm;
// swung position: beat b (int) + eighth e (0|1); ratio = long fraction of beat (0.5 straight, 0.667 triplet)
const swingPos = (b, e, ratio) => b + (e ? ratio : 0);

