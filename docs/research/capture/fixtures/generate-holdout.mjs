// Free noodling: random-walk line + occasional LH shells, never leaving a silent gap >= maxGap.
function noodle(s, t0, t1, { pedal = true, maxGap = 0.9, vel = [45, 85], scale = F_SCALE, ch = 1, src = "kbd", port = "A" } = {}) {
  let t = t0, i = Math.floor(scale.length / 2);
  let pedalDown = null;
  const o = { ch, src, port };
  while (t < t1) {
    i = Math.max(0, Math.min(scale.length - 1, i + s.pick([-2, -1, -1, 1, 1, 2, 3, -3])));
    const ioi = s.rand(0.11, Math.min(0.5, maxGap * 0.8));
    const dur = Math.min(ioi * s.rand(0.6, 1.3), maxGap * 0.9);
    s.note(t, scale[i], s.rand(vel[0], vel[1]), dur, o);
    if (s.r() < 0.12) s.chord(t, [scale[0] - 12, scale[0] - 5].map((p) => p + s.pick([0, 2, 5])), s.rand(40, 70), s.rand(0.4, 0.9), s.rand(5, 30), o);
    if (pedal && s.r() < 0.08) {
      if (pedalDown === null) { pedalDown = t + 0.05; s.cc(pedalDown, 64, 127, o); }
      else { s.cc(t - 0.02, 64, 0, o); pedalDown = null; }
    }
    t += ioi;
  }
  if (pedalDown !== null) s.cc(t1, 64, 0, o);
  return t; // last onset+ioi
}

